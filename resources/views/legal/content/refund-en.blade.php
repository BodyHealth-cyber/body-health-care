        <h2>1. General Provisions</h2>
        <p>1.1. This Refund and Cancellation Policy (the "Policy") is an official document of Body Health governing the procedure and conditions for refunding payments made by the Client for Services.</p>
        <p>1.2. This Policy has been developed in compliance with international consumer protection standards, including EU Directive 2011/83/EU on consumer rights, GDPR, and applicable regulations governing digital services and telemedicine.</p>
        <p>1.3. By accepting the Public Offer and making payment for Services, the Client confirms that they have carefully read and agree to this Policy.</p>
    </section>

    <section class="legal-section-block">
        <h2>2. Nature of Digital Medical Services</h2>
        <p>2.1. The services provided by Body Health fall within the category of digital medical and information-consultation services that are consumed at the time of their provision or to which access is granted immediately after payment.</p>
        <p>2.2. Unlike physical goods, medical consultations and telemedicine services cannot be returned in the traditional sense, as they involve the allocation of specialist time and the processing of personal health data.</p>
        <p>2.3. Body Health endeavours to ensure a fair balance of interests, guaranteeing refunds in cases where the service has not in fact been provided.</p>
    </section>

    <section class="legal-section-block">
        <h2>3. Refund Conditions for "HealthCheckup"</h2>
        <p>3.1. The "HealthCheckup" service costs $100 and is paid as a one-time fee. After payment, the medical team immediately begins processing the patient's data.</p>
        <p>3.2. <strong>A full refund is possible only if both conditions are met:</strong> the request is submitted within 24 hours of payment and the Client has not yet submitted the completed medical questionnaire for analysis.</p>
        <p>3.3. No refund will be made if the service delivery process has commenced, including questionnaire submission, data processing, or consultation.</p>
        <p>3.4. Legal basis: under Article 16(m) of EU Directive 2011/83/EU and equivalent international standards, the consumer's right of withdrawal does not apply to contracts for the supply of digital content where delivery has commenced with the consumer's explicit consent.</p>
    </section>

    <section class="legal-section-block">
        <h2>4. Cancellation and Refund Conditions for Subscriptions</h2>
        <p>4.1. The "Healthcare" and "Ambulance" packages are provided in the format of a monthly subscription with automatic renewal.</p>
        <p>4.2. <strong>Cancellation rules:</strong> the Client may cancel the subscription at any time through the Personal Account or by emailing billing@body-health.care.</p>
        <p>4.3. <strong>"15th Day" Policy:</strong></p>
        <ul>
            <li>Cancellation <strong>before the 15th</strong> of the current month means access is retained until the end of the paid period and no further charge is made.</li>
            <li>Cancellation <strong>after the 15th</strong> means access is retained until the end of the current paid period and no refund is made for remaining days.</li>
        </ul>
        <p>4.4. <strong>No pro-rata refund:</strong> Body Health does not provide pro-rata refunds for unused subscription days due to the nature of medical services, where specialist time is allocated in advance.</p>
        <p>4.5. <strong>First-month exception:</strong> if the Client purchased a subscription for the first time and requests cancellation within 48 hours of the first payment without having used any consultation, Body Health will consider the refund on an individual basis.</p>
    </section>

    <section class="legal-section-block">
        <h2>5. Exceptional Circumstances on the Provider's Side</h2>
        <p>5.1. In the event of a technical failure on the Provider's side rendering Services unavailable for more than 72 consecutive hours, the Client is entitled to a subscription extension for the number of days of unavailability.</p>
        <p>5.2. If the technical failure lasts more than 7 consecutive days, the Client may request a refund for the unused period.</p>
    </section>

    <section class="legal-section-block">
        <h2>6. Grounds for Refusal of Refund</h2>
        <p>6.1. No refund will be made if the Service was provided appropriately, the Client violated the terms of the Offer, the Client provided false medical data, the reason is disagreement with medical recommendations, or applicable refund periods have expired.</p>
        <p>6.2. <strong>Chargeback:</strong> if the Client initiates a chargeback procedure through their bank without prior contact with Body Health support, Body Health reserves the right to provide the bank with evidence of appropriate service delivery and, in cases of abuse, to restrict access to the Platform.</p>
    </section>

    <section class="legal-section-block">
        <h2>7. Medical Services and Regulatory Framework</h2>
        <p>7.1. Medical and telemedicine services are subject to special regulation distinct from the norms applicable to consumer goods.</p>
        <p>7.2. This Policy has been developed taking into account the balance between consumer rights and the specific nature of remote medical service delivery, in line with EU and international standards.</p>
    </section>

    <section class="legal-section-block">
        <h2>8. Refund Request Procedure</h2>
        <p>8.1. To initiate a refund procedure, the Client must send a written request to billing@body-health.care.</p>
        <p>8.2. The request must include the email subject "Refund Request - [Client Full Name]", the payment date and amount, the reason for the refund request, and the order or transaction number if available.</p>
        <p>8.3. Body Health will confirm receipt of the request within 1 business day and will review it within 5 business days.</p>
    </section>

    <section class="legal-section-block">
        <h2>9. Refund Method and Timeline</h2>
        <p>9.1. If a positive decision is made, the refund will be made exclusively to the bank card used for the original payment.</p>
        <p>9.2. Funds will be credited to the Client's account within 5 to 10 business days, depending on the issuing bank.</p>
        <p>9.3. Body Health does not compensate for the Client's bank fees.</p>
